import React, { useEffect, useState } from 'react'
import { authFetch } from '@veltrixsecops/app-sdk/client'
import { Badge, Card, CardBody, EmptyState, Spinner } from '@veltrixsecops/app-sdk/ui'

interface ConfigTypeSummary {
  id: string
  name: string
  description?: string
  componentTypes: string[]
}

interface AppMeta {
  appId: string
  name: string
  version: string
  configurationTypes: ConfigTypeSummary[]
}

/**
 * What this app manages in HackerOne, rendered with the platform design-system
 * components. Authoring happens in the Configuration Canvas.
 */
export default function OverviewPage() {
  const [meta, setMeta] = useState<AppMeta | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    authFetch('/api/apps/hackerone/meta')
      .then((res) => (res.ok ? res.json() : Promise.reject(new Error(`HTTP ${res.status}`))))
      .then(setMeta)
      .catch((e: Error) => setError(e.message))
      .finally(() => setLoading(false))
  }, [])

  if (loading) return <Spinner label="Loading HackerOne app details…" />
  if (error) return <EmptyState title="Failed to load app details" description={error} />
  if (!meta) return <EmptyState title="No app details available" />

  return (
    <Card>
      <CardBody>
        <p>
          Manages HackerOne program <strong>Structured Scopes</strong> as code — the assets in scope for a
          bug-bounty / vulnerability-disclosure program (asset type, identifier, bounty and submission
          eligibility, max severity and tester instruction). Author a scope in the Configuration Canvas and
          deploy it through the pipeline — validate, deploy, health check, drift detection and rollback are
          handled per configuration type. Scopes are applied over the HackerOne API
          (<code>https://api.hackerone.com/v1</code>, HTTP Basic auth, JSON:API).
        </p>
        <p>
          Each scope names its target <strong>program by handle</strong>; the handle is resolved to its program
          id via <code>GET /me/programs</code>, and the asset is upserted by identifier within that program.
        </p>

        <h3>Configuration Types</h3>
        {meta.configurationTypes.map((ct) => (
          <Card key={ct.id} variant="bordered" padding="md">
            <CardBody>
              <strong>{ct.name}</strong>
              {ct.description ? <p>{ct.description}</p> : null}
              <div>
                {ct.componentTypes.map((type) => (
                  <Badge key={type} variant="secondary" size="sm">
                    {type}
                  </Badge>
                ))}
              </div>
            </CardBody>
          </Card>
        ))}
      </CardBody>
    </Card>
  )
}
